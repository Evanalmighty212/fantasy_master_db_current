"""
lib/dataset2/partial_season_canonical.py

Family #9 canonicalization PREREQUISITE -- approved 2026-07
(research/dataset2/CANONICAL_TABLE_PROPOSAL_2026_07.md), before any
Dataset 2 canonical predictor table itself exists. Closes the two
real, disclosed gaps that proposal found:

1. GRAIN: every lib.dataset2.partial_season_traits builder that varies
   by window_n (4/6/8) and/or (position, metric_name) returns MULTIPLE
   rows per (season, player_id). build_family9_observation_wide()
   PIVOTS every one of those into a single WIDE row per (season,
   player_id), with window_n/split-type/metric_name/role-basis/tier
   encoded directly in each canonical column NAME (see
   _canonical_prefix() below), never left as a separate
   row-identifying column.

2. LAG: partial_season_traits.py itself has ZERO lag_join() calls --
   grepped directly, confirmed absent -- every one of its outputs
   describes the OBSERVATION season's own in-season split (e.g. "the
   player's final 4 games of season N"), never a preseason predictor
   for season N. build_family9_observation_wide() preserves that raw,
   same-season computation UNCHANGED (still season-N-describes-
   season-N -- this is the "raw observation-season output" the
   canonical-table proposal said must be kept). build_family9_preseason_features()
   is a SEPARATE, later step: a direct, ROW-FOR-ROW relabeling of
   every observation row from its own `season` (renamed
   `observation_season`) to `prediction_season = observation_season +
   1`. It is deliberately NOT a re-aggregation or a population lookup
   -- every output row is sourced from exactly one input row, so a
   mutation to one observation row can only ever change the ONE
   preseason row it maps to. See
   tests/test_dataset2_partial_season_canonical.py's TestLagLeakage
   for the direct proof.

NAMING: every canonical column is
`fam9_{basis}_{window_or_split}[_{position}_{metric}]_{field}`, with
`basis` in {"team", "active"}. E.g.
`fam9_team_final_4_rb_rushing_meaningful_role`,
`fam9_active_final_6_qb_passing_role_present`,
`fam9_team_final_4_wr_snap_offense_snap_share`,
`fam9_team_first_half_points_per_team_game`. The exact (raw_column ->
canonical_column) mapping is a real, generated BYPRODUCT of
build_family9_observation_wide()'s own construction loop (returned as
this function's second output) -- there is no separate, hand-written
copy of that mapping to drift out of sync with the actual renaming
code.

BOOLEAN NORMALIZATION: every boolean-shaped canonical column is cast
to pandas' nullable "boolean" dtype. TEAM-GAME-basis boolean columns
are ADDITIONALLY masked to <NA> wherever the canonical
`fam9_team_game_window_status` is not APPLICABLE -- a real, disclosed
fix for a real bug class found while writing the canonical-table
proposal: partial_season_traits.py's own `>=` threshold comparisons
against a real NaN (`team_final_n_games`/`team_final_n_active_games`
for a non-applicable row) silently evaluate to `False`, not NaN (a
real numpy/pandas comparison quirk, not a deliberate design choice in
that module), so several of ITS OWN output flags currently read as a
confident "False" for a player whose team-game window could not even
be resolved (traded, no team evidence, etc.). This module fixes that
at the canonical layer without changing partial_season_traits.py
itself. ACTIVE-GAME-basis boolean columns are NOT status-masked the
same way: `active_final_n_games == 0` is a REAL, KNOWN fact (this
player had zero real games this season), not a comparison-against-NaN
artifact -- False there is correct and stays False, verified directly
in TestBooleanNormalization.

`opportunity_qualified` (present on several raw outputs, always the
literal string `"pending"` -- see partial_season_traits.py's own
docstring) is deliberately EXCLUDED from the canonical pivot: it
carries no real information today and would sit misleadingly next to
the real, populated role-tier flags this module DOES carry through.
`team_game_window_status`/`team_final_n_games`/`team_final_n_active_games`/
`active_final_n_games` are likewise dropped from every position/metric
-scoped efficiency, role, and snap-share piece before merging -- they
are REDUNDANT with the same real values already carried once, from
the base final-N call, under `fam9_team_game_window_status` and the
window's own `fam9_{basis}_final_{n}_games`/`_active_games` columns
(verified these are computed identically regardless of position/
metric scoping, since they only ever depend on `weekly_player`, never
on which position was requested).

TEST SCOPE: tests/test_dataset2_partial_season_canonical.py proves
grain (no duplicate keys, no column-name collisions), lag/leakage
(observation-season mutation isolation, rookie nulls, the final-
historical-season future-row case), and boolean-normalization
correctness against synthetic fixtures.
"""

